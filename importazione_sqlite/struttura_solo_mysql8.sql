-- Conversione SQLite -> MySQL / MariaDB per AlterVista
-- Richiede MySQL >= 8.0.16. Importare con tabelle assenti.
-- Non elimina tabelle esistenti. Usa InnoDB e CHECK nativi ENFORCED; nessun trigger.
SET @OLD_SQL_MODE=@@SESSION.sql_mode;
SET SESSION sql_mode='STRICT_ALL_TABLES,NO_AUTO_VALUE_ON_ZERO';
SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS=1;

CREATE TABLE `Tipologia` (
  `ID` BIGINT NOT NULL AUTO_INCREMENT,
  PRIMARY KEY (`ID`),
  `Tipologia` VARBINARY(768) NOT NULL,
  UNIQUE KEY `ix_Tipologia_1` (`Tipologia`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE `Runts` (
  `CodiceFiscale` VARBINARY(768) NULL,
  UNIQUE KEY `uq_Runts_pk` (`CodiceFiscale`),
  `Denominazione` LONGTEXT CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL,
  `Cognome` LONGTEXT CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL,
  `Nome` LONGTEXT CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL,
  `IDAssociazione` BIGINT NULL,
  `Provincia` LONGTEXT CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE `CesvotTelefono` (
  `ID` BIGINT NOT NULL AUTO_INCREMENT,
  PRIMARY KEY (`ID`),
  `Denominazione` VARBINARY(768) NULL,
  `Telefono` VARBINARY(768) NULL,
  UNIQUE KEY `ix_CesvotTelefono_1` (`Denominazione`, `Telefono`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE `CesvotMail` (
  `ID` BIGINT NOT NULL AUTO_INCREMENT,
  PRIMARY KEY (`ID`),
  `Denominazione` VARBINARY(768) NULL,
  `Mail` VARBINARY(768) NULL,
  UNIQUE KEY `ix_CesvotMail_1` (`Denominazione`, `Mail`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE `Temporanea` (
  `SOGGETTO` LONGTEXT CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL,
  `MAIL` LONGTEXT CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE `MailList` (
  `ID` BIGINT NOT NULL AUTO_INCREMENT,
  PRIMARY KEY (`ID`),
  `Descrizione` VARBINARY(768) NOT NULL,
  `Note` LONGTEXT CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL,
  UNIQUE KEY `ix_MailList_1` (`Descrizione`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE `AgoraTipoEvento` (
  `ID` BIGINT NOT NULL AUTO_INCREMENT,
  PRIMARY KEY (`ID`),
  `IntestazionePagina` LONGTEXT CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE Utenti (
 ID BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 NomeIndice CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 ProfiloCifrato LONGTEXT NOT NULL,
 PasswordHash VARCHAR(255) NOT NULL,
 Ruolo VARCHAR(20) NOT NULL,
 Attivo TINYINT NOT NULL DEFAULT 1,
 VersioneSessione BIGINT NOT NULL DEFAULT 1,
 CreatoIl TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT ck_utenti_ruolo CHECK (Ruolo IN ('admin','user','esternobase','esternoevoluto')),
 CONSTRAINT ck_utenti_attivo CHECK (Attivo IN (0,1)),
 CONSTRAINT ck_utenti_esterni CHECK (Ruolo NOT IN ('esternobase','esternoevoluto') OR Attivo=0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE Pannelli (
 Codice VARCHAR(64) NOT NULL PRIMARY KEY,
 Titolo VARCHAR(100) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE UtentiPermessi (
 UtenteID BIGINT NOT NULL,
 Pannello VARCHAR(64) NOT NULL,
 Livello VARCHAR(10) NOT NULL,
 PRIMARY KEY (UtenteID,Pannello),
 FOREIGN KEY (UtenteID) REFERENCES Utenti(ID) ON DELETE CASCADE,
 FOREIGN KEY (Pannello) REFERENCES Pannelli(Codice) ON DELETE CASCADE,
 CONSTRAINT ck_permessi_livello CHECK (Livello IN ('lettura','scrittura'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE AccessiTentativi (
 Chiave CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
 Tentativi INT NOT NULL DEFAULT 0,
 Ultimo BIGINT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;


CREATE TABLE `Report` (
  `ID` BIGINT NOT NULL AUTO_INCREMENT,
  PRIMARY KEY (`ID`),
  `Password` LONGTEXT CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE `Mail` (
  `ID` BIGINT NOT NULL AUTO_INCREMENT,
  PRIMARY KEY (`ID`),
  `TipoSoggetto` VARBINARY(768) NOT NULL,
  `IDSoggetto` BIGINT NOT NULL,
  `Indirizzo` VARBINARY(768) NOT NULL,
  `PEC` BIGINT NULL DEFAULT 0,
  `Predefinito` BIGINT NULL DEFAULT 0,
  UNIQUE KEY `ix_Mail_1` (`TipoSoggetto`, `IDSoggetto`, `Indirizzo`),
  CONSTRAINT `ck_Mail_1` CHECK (BINARY `TipoSoggetto` IN ('ASSOCIAZIONE','REFERENTE','ALTRO')) ENFORCED,
  CONSTRAINT `ck_Mail_2` CHECK (`PEC` IN (0,1)) ENFORCED,
  CONSTRAINT `ck_Mail_3` CHECK (`Predefinito` IN (0,1)) ENFORCED
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE `Telefono` (
  `ID` BIGINT NOT NULL AUTO_INCREMENT,
  PRIMARY KEY (`ID`),
  `TipoSoggetto` VARBINARY(768) NOT NULL,
  `IDSoggetto` BIGINT NOT NULL,
  `Telefono` VARBINARY(768) NOT NULL,
  `Predefinito` BIGINT NULL DEFAULT 0,
  UNIQUE KEY `ix_Telefono_1` (`TipoSoggetto`, `IDSoggetto`, `Telefono`),
  CONSTRAINT `ck_Telefono_1` CHECK (BINARY `TipoSoggetto` IN ('ASSOCIAZIONE','REFERENTE','ALTRO')) ENFORCED
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE `Associazioni` (
  `ID` BIGINT NOT NULL AUTO_INCREMENT,
  PRIMARY KEY (`ID`),
  `ID_TIPOLOGIA` BIGINT NOT NULL,
  `COLONNA3` LONGTEXT CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL,
  `TAVOLO` BIGINT NOT NULL,
  `DIRETTIVO_DELEGAZIONE` BIGINT NOT NULL,
  `SOGGETTO` VARBINARY(768) NOT NULL,
  `CODICEFISCALE` LONGTEXT CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL,
  UNIQUE KEY `ix_Associazioni_1` (`SOGGETTO`),
  CONSTRAINT `fk_Associazioni_0` FOREIGN KEY (`ID_TIPOLOGIA`) REFERENCES `Tipologia` (`ID`) ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT `ck_Associazioni_1` CHECK (`TAVOLO` IN (0, 1)) ENFORCED,
  CONSTRAINT `ck_Associazioni_2` CHECK (`DIRETTIVO_DELEGAZIONE` IN (0, 1)) ENFORCED
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE `ListaMail` (
  `ID` BIGINT NOT NULL AUTO_INCREMENT,
  PRIMARY KEY (`ID`),
  `IDListaMail` BIGINT NOT NULL,
  `IDMail` BIGINT NOT NULL,
  `TipoInvio` VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL DEFAULT 'CCN',
  UNIQUE KEY `ix_ListaMail_1` (`IDListaMail`, `IDMail`),
  CONSTRAINT `fk_ListaMail_0` FOREIGN KEY (`IDMail`) REFERENCES `Mail` (`ID`) ON UPDATE CASCADE ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE `Agora` (
  `ID` BIGINT NOT NULL AUTO_INCREMENT,
  PRIMARY KEY (`ID`),
  `Data` VARBINARY(768) NOT NULL,
  `Evento` VARBINARY(768) NULL,
  `ODG` LONGTEXT CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL,
  `Verbale` LONGTEXT CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL,
  `Documenti` LONGTEXT CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL,
  `IDTipoEvento` BIGINT NOT NULL,
  UNIQUE KEY `ix_Agora_1` (`Data`, `Evento`, `IDTipoEvento`),
  CONSTRAINT `fk_Agora_0` FOREIGN KEY (`IDTipoEvento`) REFERENCES `AgoraTipoEvento` (`ID`) ON UPDATE NO ACTION ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE `AgoraPresenti` (
  `ID` BIGINT NOT NULL AUTO_INCREMENT,
  PRIMARY KEY (`ID`),
  `IDRiunioni` BIGINT NOT NULL,
  `IDAssociazione` BIGINT NOT NULL,
  `Rappresentante` VARBINARY(768) NULL,
  UNIQUE KEY `ix_AgoraPresenti_1` (`IDRiunioni`, `IDAssociazione`, `Rappresentante`),
  CONSTRAINT `fk_AgoraPresenti_0` FOREIGN KEY (`IDRiunioni`) REFERENCES `Agora` (`ID`) ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT `fk_AgoraPresenti_1` FOREIGN KEY (`IDAssociazione`) REFERENCES `Associazioni` (`ID`) ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE `Soggetti` (
  `ID` BIGINT NOT NULL AUTO_INCREMENT,
  PRIMARY KEY (`ID`),
  `ID_Associazione` BIGINT NOT NULL,
  `Nome` VARBINARY(768) NOT NULL,
  `Tipo` VARBINARY(768) NOT NULL,
  KEY `ix_Soggetti_1` (`ID_Associazione`),
  UNIQUE KEY `ix_Soggetti_2` (`ID_Associazione`, `Nome`, `Tipo`),
  CONSTRAINT `fk_Soggetti_0` FOREIGN KEY (`ID_Associazione`) REFERENCES `Associazioni` (`ID`) ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT `ck_Soggetti_1` CHECK (BINARY `Tipo` IN ('LR','AS')) ENFORCED
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;


