CREATE TABLE IF NOT EXISTS email_configurazione (
 ID BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 URLPonte VARCHAR(400) NOT NULL,
 Mittente VARCHAR(254) NOT NULL,
 NomeMittente VARCHAR(200) NOT NULL,
 Modalita ENUM('test','produzione') NOT NULL DEFAULT 'test',
 EmailTest VARCHAR(254) NOT NULL,
 Lotto INT NOT NULL DEFAULT 20,
 SegretoRef CHAR(32) NOT NULL,
 Attiva TINYINT NOT NULL DEFAULT 1,
 VerificataIl DATETIME NULL,
 CreatoIl DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK (Lotto BETWEEN 1 AND 20)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS email_messaggi (
 ID BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 Oggetto VARCHAR(250) NOT NULL,
 HTML MEDIUMTEXT NOT NULL,
 Testo MEDIUMTEXT NOT NULL,
 Versione INT NOT NULL DEFAULT 1,
 Stato ENUM('bozza','preparato') NOT NULL DEFAULT 'bozza',
 ConfigID BIGINT NULL,
 CreatoIl DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (ConfigID) REFERENCES email_configurazione(ID) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS email_destinatari (
 ID BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 MessaggioID BIGINT NOT NULL,
 MailOrigineID BIGINT NULL,
 Nome VARCHAR(768) NOT NULL,
 Email VARCHAR(254) NOT NULL,
 Tipo VARCHAR(30) NOT NULL,
 Ente VARCHAR(768) NOT NULL,
 UNIQUE KEY uq_email_dest (MessaggioID,Email),
 FOREIGN KEY (MessaggioID) REFERENCES email_messaggi(ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS email_invii (
 ID CHAR(32) NOT NULL PRIMARY KEY,
 MessaggioID BIGINT NOT NULL,
 DestinatarioID BIGINT NOT NULL,
 EmailEffettiva VARCHAR(254) NOT NULL,
 Stato ENUM('da_inviare','in_corso','inviato','da_verificare') NOT NULL DEFAULT 'da_inviare',
 CodiceHash CHAR(64) NOT NULL UNIQUE,
 ScadeIl DATETIME NOT NULL,
 IniziatoIl DATETIME NULL,
 InviatoIl DATETIME NULL,
 ConfermatoIl DATETIME NULL,
 Nota VARCHAR(300) NOT NULL DEFAULT '',
 UNIQUE KEY uq_email_invio (MessaggioID,DestinatarioID),
 INDEX ix_email_coda (MessaggioID,Stato),
 FOREIGN KEY (MessaggioID) REFERENCES email_messaggi(ID) ON DELETE RESTRICT,
 FOREIGN KEY (DestinatarioID) REFERENCES email_destinatari(ID) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
